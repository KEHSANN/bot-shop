def get_seed_translation_rows() -> list[tuple[str, str, str]]:
    """Flatten TRANSLATIONS into (key, lang_code, text_value) tuples for database seeding."""
    rows: list[tuple[str, str, str]] = []
    for key, lang_map in TRANSLATIONS.items():
        for lang_code, text_value in lang_map.items():
            rows.append((key, lang_code, text_value))
    return rows
